const touched = new Set<string>();
for (const entry of entries) {
  for (const zone of entry.zones) touched.add(`${zone} / ${entry.eventKind}`);
}

const notApplicable: NotApplicableCell[] = [];
for (const zone of zones) {
  for (const eventKind of eventKinds) {
    const key = `${zone} / ${eventKind}`;
    if (touched.has(key)) continue;
    const reason =
      specificReasons[key] ??
      `${eventKindDesc[eventKind]} does not touch the ${zone}, which ${zoneDesc[zone]}.`;
    notApplicable.push({ zone, eventKind, reason });
  }
}

// Self-checks: ids unique, every entry's zones and event kind exist in the
// universe, every specific reason names a real uncovered pair.
{
  const ids = new Set<string>();
  for (const entry of entries) {
    if (ids.has(entry.id)) throw new Error(`duplicate entry id: ${entry.id}`);
    ids.add(entry.id);
    if (!eventKindDesc[entry.eventKind]) throw new Error(`${entry.id}: unknown event kind ${entry.eventKind}`);
    for (const zone of entry.zones) {
      if (!zoneDesc[zone]) throw new Error(`${entry.id}: unknown zone ${zone}`);
    }
    for (const effect of entry.status === 'rule' ? entry.effects : []) {
      if ((effect.op === 'set_counter' || effect.op === 'adjust_counter') && !counters.includes(effect.counter)) {
        throw new Error(`${entry.id}: unknown counter ${effect.counter}`);
      }
    }
  }
  const stale: string[] = [];
  for (const key of Object.keys(specificReasons)) {
    const [zone = '', eventKind = ''] = key.split(' / ');
    if (!zoneDesc[zone] || !eventKindDesc[eventKind]) stale.push(`unknown pair: ${key}`);
    else if (touched.has(key)) stale.push(`already touched by an entry: ${key}`);
  }
  if (stale.length) throw new Error('specific reasons need attention: ' + stale.join('; '));
}

